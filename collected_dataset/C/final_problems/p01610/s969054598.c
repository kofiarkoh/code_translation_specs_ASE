#include <stdio.h>

char s[103];

char p[6][9] = {
"..rr....",
"..rr....",
"ggyybbww",
"ggyybbww",
"..oo....",
"..oo...."
};
  
void uu()
{
	int i;
	char c, d;
	
	c = p[0][2], p[0][2] = p[1][2], p[1][2] = p[1][3], p[1][3]=p[0][3], p[0][3] = c;
	c = p[2][0], d = p[2][1];
	for (i = 0; i < 6; i++) p[2][i] = p[2][(i+2) & 7];
	p[2][6] = c, p[2][7] = d;
}

void ff()
{
	char c, d;

	c = p[2][2], p[2][2] = p[3][2], p[3][2] = p[3][3], p[3][3] = p[2][3], p[2][3] = c;
	c = p[1][2], d = p[1][3];
	p[1][2] = p[3][1], p[1][3] = p[2][1], p[3][1] = p[4][3], p[2][1] = p[4][2];
	p[4][3] = p[2][4], p[4][2] = p[3][4], p[2][4] = c, p[3][4] = d;
}

void rr()
{
	char c, d;

	c = p[2][4], p[2][4] = p[3][4], p[3][4] = p[3][5], p[3][5] = p[2][5], p[2][5] = c;
	c = p[1][3], d = p[0][3];
	p[1][3] = p[3][3], p[0][3] = p[2][3], p[3][3] = p[5][3], p[2][3] = p[4][3];
	p[5][3] = p[2][6], p[4][3] = p[3][6], p[2][6] = c, p[3][6] = d;
}

void dd()
{
	int i;
	char c, d;

	c = p[4][2], p[4][2] = p[5][2], p[5][2] = p[5][3], p[5][3] = p[4][3], p[4][3] = c;
	c = p[3][5], d = p[3][4];
	for (i = 5; i >= 0; i--) p[3][i] = p[3][(i+6) & 7];
	p[3][6] = d; p[3][7] = c;
}

void bb()
{
	char c, d;
	
	c = p[2][6], p[2][6] = p[3][6], p[3][6] = p[3][7], p[3][7] = p[2][7], p[2][7] = c;
	c = p[0][2], d = p[0][3];
	p[0][2] = p[2][5], p[0][3] = p[3][5], p[2][5] = p[5][3], p[3][5] = p[5][2];
	p[5][3] = p[3][0], p[5][2] = p[2][0], p[3][0] = c, p[2][0] = d;
}

void ll()
{
	char c, d;

	c = p[2][0], p[2][0] = p[3][0], p[3][0] = p[3][1], p[3][1] = p[2][1], p[2][1] = c;
	c = p[4][2], d = p[5][2];
	p[4][2] = p[2][2], p[5][2] = p[3][2], p[2][2] = p[0][2], p[3][2] = p[1][2];
	p[0][2] = p[3][7], p[1][2] = p[2][7], p[3][7] = c, p[2][7] = d;
}
 
int main()
{
	int r;
	char *q;

	scanf("%s", q=s);
	while (*q) {
		if      (*q == 'U') uu();
		else if (*q == 'F') ff();
		else if (*q == 'R') rr();
		else if (*q == 'D') dd();
		else if (*q == 'B') bb();
		else                ll();
		q++;
	}
	for (r = 0; r < 6; r++) puts(p[r]);
	return 0;
}
