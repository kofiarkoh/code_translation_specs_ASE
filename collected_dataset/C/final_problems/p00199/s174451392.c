#include<stdio.h>
int main(){
  int n,m,i,max,k,j,z;
  char p,w;
  while(1){
    scanf("%d %d%c",&n,&m,&w);
    if(n==0&&m==0)break;
    char c[101]={0};
    for(i=0;i<m;i++){
      scanf("%c%c",&p,&w);//printf("%c",p);
      if(p=='A'){
	for(j=0;j<n;j++){
	  if(c[j]==0){
	    c[j]='A';
	    break;
	  }
	}
      }
      if(p=='B'){
	for(j=n-1;j>-1;j--){
	  if(c[j]==0&&c[j+1]!='A'&&c[j-1]!='A'){
	    c[j]='B';
	    break;  
	  }
	}
	if(j==-1){
	  for(j=0;j<n;j++){
	    if(c[j]==0){
	      c[j]='B';
	      break;
	    }
	  }
	}
      }
      if(p=='C'){
	if(i==0){
	  c[(n-(n%2))/2]='C';
	}
	else{
	  while(1){
	    j=0;
	    for(;c[j]==0;j++);
	    if(c[j+1]==0){
	      c[j+1]='C';
	      break;
	    }
	    if(c[j-1]==0){
	      c[j-1]='C';
	      break;
	    }
	  }
	}
      }
      if(p=='D'){
	if(i==0)c[0]='D';
	else{
	  z=0;
	  max=0;
	  for(j=0;j<n;j++){
	    if(c[j]!=0)continue;
	    for(k=1;k<n;k++){
	      if(j-k>-1){
		if(c[j-k]!=0)break;
	      }
	      if(j+k<n){
		if(c[j+k]!=0)break;
	      }
	    }
	    if(max<k){
	      max=k;
	      z=j;
	    }
	  }
	  c[z]='D';
	}
      }
    }
    for(i=0;i<n;i++){
      if(c[i]==0)printf("#");
      else       printf("%c",c[i]);
    }
    printf("\n");
  }
  return 0;
}