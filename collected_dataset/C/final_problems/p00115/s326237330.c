#include <stdio.h>
int main() {
	int x[5][3];
	int i, j;
	for(i = 0; i < 5; ++ i) for(j = 0; j < 3; ++ j) scanf("%d", &x[i][j]);
	int a1, a2, b1, b2, c1, c2, p, q, r, s, t;
	a1 = (x[1][1] - x[0][1]) * (x[0][0] - x[2][0]) - (x[1][0] - x[0][0]) * (x[0][1] * x[2][1]);
	b1 = (x[1][1] - x[0][1]) * (x[3][0] - x[2][0]) - (x[1][0] - x[0][0]) * (x[3][1] - x[2][1]);
	c1 = (x[1][1] - x[0][1]) * (x[4][0] - x[2][0]) - (x[1][0] - x[0][0]) * (x[4][1] - x[2][1]);
	a2 = (x[1][2] - x[0][2]) * (x[0][0] - x[2][0]) - (x[1][0] - x[0][0]) * (x[0][2] * x[2][2]);
	b2 = (x[1][2] - x[0][2]) * (x[3][0] - x[2][0]) - (x[1][0] - x[0][0]) * (x[3][2] - x[2][2]);
	c2 = (x[1][2] - x[0][2]) * (x[4][0] - x[2][0]) - (x[1][0] - x[0][0]) * (x[4][2] - x[2][2]);
	r = c2 * b1 - c1 * b2;
	p = a1 * c2 - a2 * c1;
	q = a2 * b1 - a1 * b2;
	s = (x[1][0] - x[0][0]) * r;
	t = (x[3][0] - x[2][0]) * p + (x[4][0] - x[2][0]) * q + (x[2][0] - x[0][0]) * r;
	if(0 <= t && t <= s && 0 <= p && p <= r && 0 <= q && q <= r && p + q <= r) printf("HIT\n");
	else printf("MISS\n");
	return 0;
}