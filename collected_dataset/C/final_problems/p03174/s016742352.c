int cntbit ( int bit )
{
  int n = 0;
  int tmp,i;

  for ( i = 0; i < 8; i++ ) {
    tmp = (bit&(15<<(4*i))) >> ( 4*i);
    n += BT[tmp];
  }

  return n;

}

int matching ( int x, int n )
{
  if (S[x] != -1 ) return S[x];

  int i,b,bitn;
  long tmp = 0;

  bitn = cntbit(x);
  for ( i = 0; i < n; i++ ) {
    if ( x & (1<<i) ) {
      b = ( x & (~(1<<i)));
      tmp += matching(b,n)*A[bitn-1][i];
    }
  }

  return S[x] = tmp%QQQ;
}

