{
  int i,j,n;

  scanf("%d",&n);

  for ( i = 0; i < n; i++ ) {
    for (j = 0; j < n; j++ ) scanf("%d", &A[i][j]);
  }

  for ( i = 0; i < ( 1<< n ); i++ ) S[i] = -1;
  S[0] = 1;

  printf("%d\n",matching((1<<n)-1,n));

  return 0;
}
