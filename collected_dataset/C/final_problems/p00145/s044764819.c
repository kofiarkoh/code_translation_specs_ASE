#include<stdio.h>
int main(){
  int n,d1[100],d2[100],m11=-1,m12=-1,m21=-1,m22=-1,
    c=0,i,j,i11,i12,i21,i22,t;
  scanf("%d",&n);
  for(i=0;i<n;i++){
    scanf("%d %d",&d1[i],&d2[i]);
  }
  for(i=1;i<n;i++){
    for(j=0;j<n;j++){
      if(m12<d1[j]){
	m12=d1[j];
	i12=j;
	if(m11<=m12){
	  t=m12;
	  m12=m11;
	  m11=t;
	  i12=i11;
	  i11=j;
	}
      }
      if(m22<=d2[j]){
	m22=d2[j];
	i22=j;
	if(m21<m22){
	  t=m22;
	  m22=m21;
	  m21=t;
	  i22=i21;
	  i21=j;
	}
      }
    }
    if(i11==i21){
      if(m11<m21){
	i11=i12;
      }
      else{
	i21=i22;
      }
    }
    c+=d1[i11]*d2[i21]*d2[i11]*d1[i21];
    d1[i11]=0;
    d2[i21]=d2[i11];
    d2[i11]=0;
    m11=-1;
    m21=-1;
    m12=-1;
    m22=-1;
  }
  printf("%d\n",c);
  return 0;
}