#include<stdio.h>
int main(){
	int s,i;
	long long int a[2001];
	scanf("%d",&s);
	a[2]=0;a[1]=0;a[3]=1;	
	if (s==3) printf("1\n");
	else {
		for (i=4;i<=s;i++)
		{
			a[i]=a[i-1]+a[i-3];//завязано на свойстве коэффициентов бинома ньютона, надо жоко заметить 
				 	   //закономерность, она совсем неочевидна, на мой взгляд, и под общий случай 
					   //хз как подобрать, шагать назад на другие kонстанты наверно
			a[i]=a[i]%1000000007;
		}
		printf("%lld\n",a[s]);
	}
	return 0;
}
